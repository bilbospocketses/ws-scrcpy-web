#!/usr/bin/env node
// scripts/refresh-iana-tlds.mjs
//
// Regenerates src/common/ianaTlds.ts, IANA's list of delegated top-level
// domains, which a Local HTTPS hostname certificate may not be issued for
// (src/common/publicSuffix.ts says why). The app never fetches the list at run
// time: it ships the copy this script writes.
//
//   node scripts/refresh-iana-tlds.mjs
//
// then review the diff (TLDs come and go a few times a year) and commit the
// regenerated module. The list's own first line, `# Version <n>, Last Updated
// <date>`, is kept in the module, so the copy in the tree always says which
// release of the list it is.
//
// Checks before writing anything, exit 1 with nothing written if one fails:
// the first line is IANA's version header, every other line is one ASCII label
// (letters, digits, hyphens), there are no duplicates, and the list is not
// implausibly short (a truncated download must not quietly allow every TLD it
// lost).

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.join(__dirname, '..');
const OUT = path.join(REPO_ROOT, 'src', 'common', 'ianaTlds.ts');

export const IANA_TLDS_URL = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';

/** Far below the ~1,400 IANA lists: only a broken download comes in under it. */
const MIN_TLDS = 1000;

/**
 * Delegated TLDs spelled the British way, written with a `spelling: allow`
 * marker so the American-spelling gate (CI) passes a verbatim external name.
 * Add a new one here if a refresh brings one in and the gate names it.
 */
const BRITISH_SPELLED_TLDS = new Set(['theatre']);

/**
 * Parse IANA's file: its version header and the labels, lower-cased. Throws on
 * anything that is not the format described in this file's header comment.
 */
export function parseTldList(text) {
    const lines = text.split(/\r?\n/).filter((l) => l.trim() !== '');
    const header = lines[0] ?? '';
    if (!/^# Version \d+, Last Updated .+$/.test(header)) {
        throw new Error(`the first line is not IANA's version header: ${JSON.stringify(header)}`);
    }
    const tlds = [];
    const seen = new Set();
    for (const line of lines.slice(1)) {
        if (!/^[A-Za-z0-9-]+$/.test(line)) throw new Error(`not a TLD label: ${JSON.stringify(line)}`);
        const tld = line.toLowerCase();
        if (seen.has(tld)) throw new Error(`listed twice: ${tld}`);
        seen.add(tld);
        tlds.push(tld);
    }
    if (tlds.length < MIN_TLDS) throw new Error(`only ${tlds.length} TLDs; expected at least ${MIN_TLDS}`);
    return { header, tlds };
}

/** The TypeScript module for `parseTldList`'s result. */
export function renderTldModule({ header, tlds }) {
    const entries = tlds.map((t) =>
        BRITISH_SPELLED_TLDS.has(t)
            ? `    '${t}', // spelling: allow -- a delegated TLD, as IANA lists it`
            : `    '${t}',`,
    );
    return `// GENERATED by scripts/refresh-iana-tlds.mjs from ${IANA_TLDS_URL}.
// Do not edit by hand: rerun the script. src/common/publicSuffix.ts says what it is for.

/** The list's own first line, as IANA publishes it: which release this copy is. */
export const IANA_TLDS_VERSION = '${header}';

/** Every delegated top-level domain, lower case, A-labels for internationalized ones (\`xn--…\`). */
export const IANA_TLDS: ReadonlySet<string> = new Set([
${entries.join('\n')}
]);
`;
}

/** Fetch the list, check it and write the module. */
export async function refresh(out = OUT) {
    const res = await fetch(IANA_TLDS_URL);
    if (!res.ok) throw new Error(`${IANA_TLDS_URL} answered ${res.status}`);
    const parsed = parseTldList(await res.text());
    fs.writeFileSync(out, renderTldModule(parsed));
    console.log('wrote %s: %d TLDs, %s', path.relative(REPO_ROOT, out), parsed.tlds.length, parsed.header);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        await refresh();
    } catch (err) {
        console.error('refresh-iana-tlds: %s', err instanceof Error ? err.message : String(err));
        process.exit(1);
    }
}
